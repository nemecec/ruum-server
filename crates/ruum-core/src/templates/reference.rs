//! The `app.yaml` reference of the gallery (`gallery/reference/app-yaml.md`), generated from
//! the descriptions of `contracts/manifests/app.schema.json`, so it cannot drift: the test
//! `gallery_reference_is_current` compares the file with [`generate`], and every property of
//! the schema has a line. To write the file again, run that test with
//! `RUUM_WRITE_GALLERY_REFERENCE=1`.
//!
//! Each line is one field: its path (`bindings.<name>.role`; `<name>` stands for a key the
//! author chooses, `[]` for an item of a list), its type or values, whether it is required, and
//! the schema's description. A `$ref` is followed; the branches of `oneOf` and `anyOf` are
//! listed under the same path.

use serde_json::{Map, Value};
use std::collections::BTreeSet;

/// The stable URL of the schema, for the first line of an `app.yaml`.
pub const APP_SCHEMA_URL: &str = crate::apps::manifest::SCHEMA_ID;
/// The deepest nesting that the generator follows.
const MAX_DEPTH: usize = 12;

/// One field of the reference.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Row {
    pub path: String,
    pub ty: String,
    pub required: bool,
    pub description: String,
}

/// The reference of the compiled-in `app.schema.json`.
pub fn generate() -> String {
    let schema: Value =
        serde_json::from_str(crate::apps::manifest::SCHEMA_JSON).expect("app.schema.json is JSON");
    generate_from(&schema)
}

/// The reference of `schema`.
pub fn generate_from(schema: &Value) -> String {
    let rows = rows(schema);
    let mut out = String::new();
    out.push_str("# app.yaml reference\n\n");
    out.push_str(
        "Generated from `contracts/manifests/app.schema.json` by `ruum_core::templates::reference`. \
         Do not edit this file: the test `gallery_reference_is_current` fails when it differs \
         from the schema. To write it again, run that test with `RUUM_WRITE_GALLERY_REFERENCE=1`.\n\n",
    );
    out.push_str(&format!(
        "Start every `app.yaml` with this line, so an editor checks the file as you type:\n\n\
         ```yaml\n# yaml-language-server: $schema={APP_SCHEMA_URL}\n```\n\n"
    ));
    if let Some(d) = schema.get("description").and_then(Value::as_str) {
        out.push_str(&one_line(d));
        out.push_str("\n\n");
    }
    out.push_str(
        "`<name>` stands for a key that you choose (a binding, a role, a secret); `[]` for an item \
         of a list.\n\n",
    );
    out.push_str("| Field | Type | Required | Description |\n|---|---|---|---|\n");
    for r in rows {
        out.push_str(&format!(
            "| `{}` | {} | {} | {} |\n",
            r.path,
            cell(&r.ty),
            if r.required { "yes" } else { "" },
            cell(&r.description)
        ));
    }
    out
}

/// The fields of `schema`, in the order of the reference (each object's properties by name).
pub fn rows(schema: &Value) -> Vec<Row> {
    let mut out = Vec::new();
    let mut seen = BTreeSet::new();
    descend(schema, schema, "", &mut out, &mut seen, 0);
    out
}

fn one_line(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn cell(s: &str) -> String {
    one_line(s).replace('|', "\\|")
}

/// The schema at `node`, with a local `$ref` (`#/$defs/<name>`) merged under its own keys.
fn resolve(root: &Value, node: &Value) -> Map<String, Value> {
    let mut out = Map::new();
    let Some(obj) = node.as_object() else {
        return out;
    };
    if let Some(r) = obj.get("$ref").and_then(Value::as_str)
        && let Some(name) = r.strip_prefix("#/$defs/")
        && let Some(target) = root.get("$defs").and_then(|d| d.get(name))
    {
        out = resolve(root, target);
        out.insert("x-ref".into(), Value::String(name.to_string()));
    }
    for (k, v) in obj {
        if k != "$ref" {
            out.insert(k.clone(), v.clone());
        }
    }
    out
}

fn type_text(s: &Map<String, Value>) -> String {
    if let Some(c) = s.get("const") {
        return format!("`{c}`");
    }
    if let Some(e) = s.get("enum").and_then(Value::as_array) {
        return e
            .iter()
            .map(|v| match v {
                Value::String(t) => format!("`{t}`"),
                other => format!("`{other}`"),
            })
            .collect::<Vec<_>>()
            .join(", ");
    }
    let mut t = match s.get("type") {
        Some(Value::String(t)) => t.clone(),
        Some(Value::Array(a)) => a
            .iter()
            .filter_map(Value::as_str)
            .collect::<Vec<_>>()
            .join(" or "),
        _ if s.contains_key("oneOf") || s.contains_key("anyOf") => "one of the forms below".into(),
        _ => String::new(),
    };
    if let Some(r) = s.get("x-ref").and_then(Value::as_str) {
        t = if t.is_empty() {
            r.to_string()
        } else {
            format!("{t} ({r})")
        };
    }
    if t == "array"
        && let Some(items) = s.get("items").and_then(Value::as_object)
    {
        let inner = type_text(items);
        if !inner.is_empty() {
            t = format!("list of {inner}");
        }
    }
    t
}

fn description(s: &Map<String, Value>, root: &Value) -> String {
    if let Some(d) = s.get("description").and_then(Value::as_str) {
        return one_line(d);
    }
    // A `$ref` without its own description takes the target's.
    if let Some(r) = s.get("x-ref").and_then(Value::as_str)
        && let Some(d) = root
            .get("$defs")
            .and_then(|d| d.get(r))
            .and_then(|t| t.get("description"))
            .and_then(Value::as_str)
    {
        return one_line(d);
    }
    String::new()
}

/// Adds the rows below the (resolved) schema `node` at `path`.
fn descend(
    root: &Value,
    node: &Value,
    path: &str,
    out: &mut Vec<Row>,
    seen: &mut BTreeSet<String>,
    depth: usize,
) {
    if depth > MAX_DEPTH {
        return;
    }
    let s = resolve(root, node);
    let required: BTreeSet<&str> = s
        .get("required")
        .and_then(Value::as_array)
        .map(|a| a.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    if let Some(props) = s.get("properties").and_then(Value::as_object) {
        for (k, child) in props {
            let p = if path.is_empty() {
                k.clone()
            } else {
                format!("{path}.{k}")
            };
            let c = resolve(root, child);
            if seen.insert(p.clone()) {
                out.push(Row {
                    path: p.clone(),
                    ty: type_text(&c),
                    required: required.contains(k.as_str()),
                    description: description(&c, root),
                });
            }
            descend(root, child, &p, out, seen, depth + 1);
        }
    }
    if let Some(ap) = s.get("additionalProperties").filter(|v| v.is_object()) {
        descend(root, ap, &format!("{path}.<name>"), out, seen, depth + 1);
    }
    if let Some(items) = s.get("items").filter(|v| v.is_object()) {
        descend(root, items, &format!("{path}[]"), out, seen, depth + 1);
    }
    for key in ["oneOf", "anyOf"] {
        if let Some(branches) = s.get(key).and_then(Value::as_array) {
            for b in branches {
                descend(root, b, path, out, seen, depth + 1);
            }
        }
    }
}

/// Every property name anywhere in `schema` (under any `properties`), for the test that each
/// has a line.
pub fn property_names(schema: &Value) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    fn walk(v: &Value, out: &mut BTreeSet<String>) {
        match v {
            Value::Object(o) => {
                if let Some(Value::Object(p)) = o.get("properties") {
                    out.extend(p.keys().cloned());
                }
                for (k, child) in o {
                    if k != "examples" {
                        walk(child, out);
                    }
                }
            }
            Value::Array(a) => a.iter().for_each(|c| walk(c, out)),
            _ => {}
        }
    }
    walk(schema, &mut out);
    out
}
