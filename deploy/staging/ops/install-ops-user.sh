#!/usr/bin/env bash
# Sets up the ruum-ops user on the build server (review 2 O-1, review 1 S-2). Run once with sudo
# on the build server, by the person or the orchestrator:
#
#   sudo bash install-ops-user.sh <commit>      install or move /opt/ruum-staging/current to <commit>
#
# - ruum-ops: a system user with home /home/ruum-ops (0700). The kubeconfig, talosconfig and
#   plans live in ~ruum-ops/.ruum-staging (0700); build jobs run as `ruum` and cannot read them.
# - /opt/ruum-staging: a root-owned clone of github.com/nemecec/ruum-server at a pushed commit.
#   ruum-ops runs the scripts from there, never from the `ruum` user's writable checkouts.
# - sudoers: `ruum` may run exactly /opt/ruum-staging/current/deploy/staging/remote.sh as
#   ruum-ops, and this script for a new commit, nothing else.
# - The tools (setup.sh) are installed into ~ruum-ops/.local/bin.
set -euo pipefail
[[ $EUID -eq 0 ]] || { echo "run with sudo" >&2; exit 1; }
commit="${1:?commit of github.com/nemecec/ruum-server}"
[[ "$commit" =~ ^[0-9a-f]{40}$ ]] || { echo "give the full 40-character commit" >&2; exit 1; }
REPO=https://github.com/nemecec/ruum-server.git

id ruum-ops >/dev/null 2>&1 || useradd --system --create-home --home-dir /home/ruum-ops --shell /bin/bash ruum-ops
chmod 700 /home/ruum-ops

mkdir -p /opt/ruum-staging
[[ -d /opt/ruum-staging/repo/.git ]] || git clone --quiet --no-checkout "$REPO" /opt/ruum-staging/repo
git -C /opt/ruum-staging/repo fetch --quiet origin '+refs/heads/*:refs/remotes/origin/*'
git -C /opt/ruum-staging/repo cat-file -e "$commit^{commit}" || { echo "commit $commit is not on GitHub" >&2; exit 1; }
if [[ ! -d "/opt/ruum-staging/${commit:?}" ]]; then
  git -C /opt/ruum-staging/repo worktree add --detach "/opt/ruum-staging/${commit:?}" "$commit" >/dev/null
fi
ln -sfn "/opt/ruum-staging/${commit:?}" /opt/ruum-staging/current
chown -R root:root /opt/ruum-staging
chmod -R go-w /opt/ruum-staging

cat >/etc/sudoers.d/ruum-staging <<'SUDO'
# Generated by deploy/staging/ops/install-ops-user.sh. Build jobs (user ruum) can run the
# staging steps as ruum-ops, but cannot read ruum-ops' files.
ruum ALL=(ruum-ops) NOPASSWD: /opt/ruum-staging/current/deploy/staging/remote.sh *
ruum ALL=(root) NOPASSWD: /opt/ruum-staging/current/deploy/staging/ops/install-ops-user.sh *
SUDO
chmod 440 /etc/sudoers.d/ruum-staging
visudo -cf /etc/sudoers.d/ruum-staging >/dev/null

sudo -u ruum-ops -H bash /opt/ruum-staging/current/deploy/staging/setup.sh >/dev/null
echo "ruum-ops is ready at $commit (remote.sh steps run from /opt/ruum-staging/current)"
