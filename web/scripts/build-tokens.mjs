// Builds the design tokens into src/design/generated/ and the theme's files into public/.
//
// The tokens are the core files of src/design/tokens/*.tokens.json (W3C Design Tokens format)
// with the default theme package over them (src/design/themes/<DEFAULT_THEME>/, design 12.6;
// theme-lib.mjs). The theme is checked first (check-theme.mjs): a failing theme stops the build.
//
// Output, all committed, so tests, the type check and Ladle need no build step:
//   src/design/generated/tokens.css   the theme's @font-face rules and the CSS custom properties:
//                                     light on :root, dark under prefers-color-scheme and data-theme
//   src/design/generated/tokens.ts    the values for code, and the theme's name
//   src/design/generated/brand.ts     the theme's wordmark as a shape tree (Brand draws it)
//   public/favicon.svg, public/<app icons>, public/manifest.webmanifest
//
//   node scripts/build-tokens.mjs           write the output
//   node scripts/build-tokens.mjs --check   fail when the committed output is out of date
import fs from 'node:fs'
import path from 'node:path'
import StyleDictionary from 'style-dictionary'
import { checkTheme } from './check-theme.mjs'
import { DEFAULT_THEME, effectiveTokens, flatten, fontSubsets, loadCore, loadTheme, parseSvg, schemes, themeDir, web } from './theme-lib.mjs'

const generated = path.join(web, 'src/design/generated')
const pub = path.join(web, 'public')
const check = process.argv.includes('--check')

const core = loadCore()
const dir = themeDir(DEFAULT_THEME)
const verdict = checkTheme(dir, core)
if (verdict.problems.length) {
  console.error(`The default theme ${DEFAULT_THEME} is refused:\n${verdict.problems.map((p) => `  - ${p}`).join('\n')}`)
  process.exit(1)
}
const theme = loadTheme(dir)
const { manifest } = theme
const trees = effectiveTokens(theme, core)

const header = `/* Generated by scripts/build-tokens.mjs from src/design/tokens and the theme ${manifest.id}. Do not edit. */\n`

/** A Style Dictionary over the merged trees (base and one colour set). */
function dictionary(scheme) {
  const tokens = structuredClone({ ...trees.base, ...trees[scheme] })
  delete tokens.$description
  return new StyleDictionary({
    tokens,
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: {
      css: {
        transformGroup: 'css',
        files: [{ destination: 'x.css', format: 'css/variables', options: { outputReferences: false, showFileHeader: false } }],
      },
    },
  })
}

/** The CSS custom properties of one scheme; with `only`, just the tokens whose path is in it. */
async function cssLines(scheme, only) {
  const sd = dictionary(scheme)
  if (only) sd.platforms.css.files[0].filter = (t) => only.has(t.path.join('.'))
  const [out] = await sd.formatPlatform('css')
  return out.output
    .split('\n')
    .filter((l) => l.trim().startsWith('--'))
    .map((l) => l.trim())
}

async function values(scheme) {
  const dict = await dictionary(scheme).getPlatformTokens('css')
  return dict.allTokens.map((t) => [t.name, t.$value ?? t.value])
}

const block = (selector, lines, extra = []) => `${selector} {\n${[...extra, ...lines].map((l) => `  ${l}`).join('\n')}\n}\n`

const light = await cssLines('light')
// Dark sets only what differs by scheme: the tokens of the colour file.
const dark = await cssLines('dark', new Set(flatten(trees.dark).map((t) => t.path)))

// The theme's fonts. The URLs are relative to src/design/generated/, so Vite bundles the files.
const fontFaces = (manifest.fonts ?? [])
  .map(
    (f) =>
      `@font-face {\n  font-family: '${f.family}';\n  font-style: ${f.style};\n  font-weight: ${f.weight};\n  font-display: swap;\n` +
      `  src: url('../themes/${manifest.id}/${f.src}') format('woff2');\n  unicode-range: ${fontSubsets[f.subset]};\n}\n`,
  )
  .join('')

const css =
  header +
  (fontFaces ? `/* The fonts of the theme: self-hosted, nothing loads from a font host. */\n${fontFaces}` : '') +
  '/* Light is the default; dark follows the system unless the person forces a theme (data-theme on <html>). */\n' +
  block(':root', light, ['color-scheme: light dark;']) +
  block(":root[data-theme='light']", [], ['color-scheme: light;']) +
  '@media (prefers-color-scheme: dark) {\n' +
  block(":root:not([data-theme='light'])", dark)
    .split('\n')
    .map((l) => (l ? `  ${l}` : l))
    .join('\n') +
  '}\n' +
  block(":root[data-theme='dark']", dark, ['color-scheme: dark;'])

const base = await values('light')
const ts =
  `// Generated by scripts/build-tokens.mjs from src/design/tokens and the theme ${manifest.id}. Do not edit.\n` +
  '// Values for code that cannot use CSS (for example a media query in matchMedia). Colours are the\n' +
  '// light set: in CSS use the custom property, which follows the theme.\n\n' +
  `export const themes = ${JSON.stringify(schemes)} as const\n\n` +
  '/** The theme package the tokens come from (design 12.6). */\n' +
  `export const theme = ${JSON.stringify({ id: manifest.id, name: manifest.name, version: manifest.version })} as const\n\n` +
  'export const tokens = {\n' +
  base.map(([k, v]) => `  '${k}': ${JSON.stringify(String(v))},`).join('\n') +
  '\n} as const\n\n' +
  'export type TokenName = keyof typeof tokens\n\n' +
  '/** `var(--name)` of a token, for the rare style that code must set. */\n' +
  'export function cssVar(name: TokenName): string {\n  return `var(--${name})`\n}\n'

// The wordmark as a tree of shapes with React prop names. check-theme.mjs allowed only plain
// shapes and colours as currentColor, hex or var(--color-*), so drawing it runs no theme code.
const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
function shape(node) {
  return {
    tag: node.tag,
    props: Object.fromEntries(Object.entries(node.attrs).filter(([k]) => k !== 'xmlns').map(([k, v]) => [camel(k), v])),
    children: node.children.filter((c) => c.tag !== 'title').map(shape),
  }
}
let wordmark = null
if (manifest.assets.wordmark) {
  const { tree } = parseSvg(fs.readFileSync(path.join(dir, manifest.assets.wordmark), 'utf8'))
  const { tag: _tag, ...rest } = shape(tree)
  wordmark = rest
}
const brand =
  `// Generated by scripts/build-tokens.mjs from the theme ${manifest.id}. Do not edit.\n\n` +
  '/** One shape of the wordmark: an SVG element with React props. */\n' +
  'export interface BrandShape {\n  tag: string\n  props: Record<string, string>\n  children: BrandShape[]\n}\n\n' +
  "/** The theme's wordmark (null: the theme has none, and Brand shows the product name as text). */\n" +
  `export const wordmark: Omit<BrandShape, 'tag'> | null = ${JSON.stringify(wordmark, null, 2)}\n`

// The theme's icons, served from the site root.
const icons = manifest.assets.appIcons ?? []
const publicName = (icon) => (icon.purpose === 'apple-touch' ? 'apple-touch-icon.png' : `icon-${icon.size}.png`)
const webmanifest =
  JSON.stringify(
    {
      name: 'Ruum',
      short_name: 'Ruum',
      start_url: '/',
      display: 'standalone',
      background_color: trees.light.color.canvas.$value.hex,
      theme_color: trees.light.color.surface.$value.hex,
      icons: [
        { src: '/favicon.svg', sizes: 'any', type: 'image/svg+xml' },
        ...icons
          .filter((i) => i.purpose !== 'apple-touch')
          .map((i) => ({ src: `/${publicName(i)}`, sizes: `${i.size}x${i.size}`, type: 'image/png', purpose: i.purpose ?? 'any' })),
      ],
    },
    null,
    2,
  ) + '\n'

const outputs = [
  [path.join(generated, 'tokens.css'), css],
  [path.join(generated, 'tokens.ts'), ts],
  [path.join(generated, 'brand.ts'), brand],
  [path.join(pub, 'favicon.svg'), fs.readFileSync(path.join(dir, manifest.assets.favicon))],
  [path.join(pub, 'manifest.webmanifest'), webmanifest],
  ...icons.map((i) => [path.join(pub, publicName(i)), fs.readFileSync(path.join(dir, i.src))]),
]

const stale = []
for (const [target, content] of outputs) {
  const want = Buffer.isBuffer(content) ? content : Buffer.from(content)
  if (check) {
    const now = fs.existsSync(target) ? fs.readFileSync(target) : Buffer.alloc(0)
    if (!now.equals(want)) stale.push(path.relative(web, target))
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, want)
  }
}
if (stale.length) {
  console.error(`Out of date: ${stale.join(', ')}. Run 'npm run tokens' in web/ and commit the result.`)
  process.exit(1)
}
if (!check) console.log(`tokens: theme ${manifest.id} ${manifest.version}, ${light.length} light, ${dark.length} dark properties -> src/design/generated/, public/`)
