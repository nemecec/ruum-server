// Builds the design tokens (src/design/tokens/*.tokens.json, W3C Design Tokens format) into
// src/design/generated/: tokens.css (CSS custom properties, light on :root, dark under
// prefers-color-scheme and data-theme) and tokens.ts (the values for code). The output is
// committed, so tests, the type check and Ladle need no build step.
//
//   node scripts/build-tokens.mjs           write the output
//   node scripts/build-tokens.mjs --check   fail when the committed output is out of date
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import StyleDictionary from 'style-dictionary'

const web = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const tokens = path.join(web, 'src/design/tokens')
const generated = path.join(web, 'src/design/generated')
const check = process.argv.includes('--check')

/** The themes: each is one colour set over the base tokens. A new theme is one more file. */
const themes = ['light', 'dark']

const header = '/* Generated by scripts/build-tokens.mjs from src/design/tokens. Do not edit. */\n'

/** The CSS custom properties of `files`, only for tokens defined in `own` (or all). */
async function cssLines(files, own) {
  const sd = new StyleDictionary({
    source: files.map((f) => path.join(tokens, f)),
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: {
      css: {
        transformGroup: 'css',
        files: [
          {
            destination: 'x.css',
            format: 'css/variables',
            filter: own ? (t) => t.filePath.endsWith(own) : undefined,
            options: { outputReferences: false, showFileHeader: false },
          },
        ],
      },
    },
  })
  const [out] = await sd.formatPlatform('css')
  return out.output
    .split('\n')
    .filter((l) => l.trim().startsWith('--'))
    .map((l) => l.trim())
}

async function values(files) {
  const sd = new StyleDictionary({
    source: files.map((f) => path.join(tokens, f)),
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: { css: { transformGroup: 'css' } },
  })
  const dict = await sd.getPlatformTokens('css')
  return dict.allTokens.map((t) => [t.name, t.$value ?? t.value])
}

const block = (selector, lines, extra = []) => `${selector} {\n${[...extra, ...lines].map((l) => `  ${l}`).join('\n')}\n}\n`

const light = await cssLines(['base.tokens.json', 'color.light.tokens.json'])
const dark = await cssLines(['base.tokens.json', 'color.dark.tokens.json'], 'color.dark.tokens.json')

const css =
  header +
  '/* Light is the default; dark follows the system unless the person forces a theme (data-theme on <html>). */\n' +
  block(':root', light, ['color-scheme: light dark;']) +
  block(":root[data-theme='light']", [], ['color-scheme: light;']) +
  '@media (prefers-color-scheme: dark) {\n' +
  block(":root:not([data-theme='light'])", dark)
    .split('\n')
    .map((l) => (l ? `  ${l}` : l))
    .join('\n') +
  '}\n' +
  block(":root[data-theme='dark']", dark, ['color-scheme: dark;'])

const base = await values(['base.tokens.json', 'color.light.tokens.json'])
const ts =
  '// Generated by scripts/build-tokens.mjs from src/design/tokens. Do not edit.\n' +
  '// Values for code that cannot use CSS (for example a media query in matchMedia). Colours are the\n' +
  '// light set: in CSS use the custom property, which follows the theme.\n\n' +
  `export const themes = ${JSON.stringify(themes)} as const\n\n` +
  'export const tokens = {\n' +
  base.map(([k, v]) => `  '${k}': ${JSON.stringify(String(v))},`).join('\n') +
  '\n} as const\n\n' +
  'export type TokenName = keyof typeof tokens\n\n' +
  '/** `var(--name)` of a token, for the rare style that code must set. */\n' +
  'export function cssVar(name: TokenName): string {\n  return `var(--${name})`\n}\n'

const outputs = { 'tokens.css': css, 'tokens.ts': ts }
let stale = []
for (const [file, text] of Object.entries(outputs)) {
  const target = path.join(generated, file)
  if (check) {
    const now = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
    if (now !== text) stale.push(path.relative(web, target))
  } else {
    fs.mkdirSync(generated, { recursive: true })
    fs.writeFileSync(target, text)
  }
}
if (stale.length) {
  console.error(`Out of date: ${stale.join(', ')}. Run 'npm run tokens' in web/ and commit the result.`)
  process.exit(1)
}
if (!check) console.log(`tokens: ${light.length} light, ${dark.length} dark properties -> src/design/generated/`)
